// Draws the tray icons (a rounded square with three linked nodes, and the same with a dot for "waiting on you") and
// writes them as base64 PNGs into electron/icons.ts, so the app ships no binary asset. Run: node scripts/make-icons.mjs
import { writeFileSync } from 'node:fs'
import { deflateSync } from 'node:zlib'

const SIZE = 64
const SS = 4 // supersampling

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})
const crc = (buf) => {
  let c = 0xffffffff
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type), data])
  const sum = Buffer.alloc(4)
  sum.writeUInt32BE(crc(body))
  return Buffer.concat([len, body, sum])
}
const png = (rgba) => {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(SIZE, 0)
  ihdr.writeUInt32BE(SIZE, 4)
  ihdr[8] = 8
  ihdr[9] = 6
  const raw = Buffer.alloc((SIZE * 4 + 1) * SIZE)
  for (let y = 0; y < SIZE; y++) {
    raw[y * (SIZE * 4 + 1)] = 0
    rgba.copy(raw, y * (SIZE * 4 + 1) + 1, y * SIZE * 4, (y + 1) * SIZE * 4)
  }
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))])
}

const hex = (h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)]
const PURPLE = hex('#bd93f9')
const DARK = hex('#21222c')
const ORANGE = hex('#ffb86c')

const nodes = [[20, 40], [44, 40], [32, 18]]
const inRoundRect = (x, y) => {
  const r = 14
  const cx = Math.min(Math.max(x, r), SIZE - r)
  const cy = Math.min(Math.max(y, r), SIZE - r)
  return (x - cx) ** 2 + (y - cy) ** 2 <= r * r
}
const nearSegment = (x, y, [ax, ay], [bx, by], w) => {
  const dx = bx - ax
  const dy = by - ay
  const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
  return (x - (ax + t * dx)) ** 2 + (y - (ay + t * dy)) ** 2 <= w * w
}

function draw(dot) {
  const out = Buffer.alloc(SIZE * SIZE * 4)
  for (let py = 0; py < SIZE; py++) {
    for (let px = 0; px < SIZE; px++) {
      let r = 0, g = 0, b = 0, a = 0
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const x = px + (sx + 0.5) / SS
          const y = py + (sy + 0.5) / SS
          let col
          if (dot && (x - 50) ** 2 + (y - 14) ** 2 <= 11 * 11) col = (x - 50) ** 2 + (y - 14) ** 2 <= 8 * 8 ? ORANGE : DARK
          else if (!inRoundRect(x, y)) continue
          else if (nodes.some(([nx, ny]) => (x - nx) ** 2 + (y - ny) ** 2 <= 6 * 6)) col = DARK
          else if (nearSegment(x, y, nodes[0], nodes[1], 2) || nearSegment(x, y, nodes[1], nodes[2], 2) || nearSegment(x, y, nodes[2], nodes[0], 2)) col = DARK
          else col = PURPLE
          r += col[0]; g += col[1]; b += col[2]; a += 255
        }
      }
      const n = SS * SS
      const i = (py * SIZE + px) * 4
      const cov = a / 255
      out[i] = cov ? Math.round(r / cov) : 0
      out[i + 1] = cov ? Math.round(g / cov) : 0
      out[i + 2] = cov ? Math.round(b / cov) : 0
      out[i + 3] = Math.round(a / n)
    }
  }
  return png(out).toString('base64')
}

writeFileSync(
  new URL('../electron/icons.ts', import.meta.url),
  `// Generated by scripts/make-icons.mjs: the tray icons as base64 PNGs. Do not edit.\nexport const ICON = '${draw(false)}'\nexport const ICON_WAITING = '${draw(true)}'\n`,
)
