// protoc-gen-flagdocs is a buf plugin (proto/buf.gen.yaml) that writes each proto package's field comments into
// its generated Go package as FieldDocs, so the generated `mesh` can describe every flag in `mesh help <command>`
// with the sentence the schema already says. The compiled descriptors carry no comments; this is how they get
// to run time. Nothing is written twice: a comment edited in a .proto reaches the help on the next `buf generate`.
package main

import (
	"fmt"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		type pkg struct {
			path protogen.GoImportPath
			name string
			dir  string
			docs map[string]string
		}
		pkgs := map[protogen.GoImportPath]*pkg{}
		var order []*pkg
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			p := pkgs[f.GoImportPath]
			if p == nil {
				dir := f.Desc.Path()
				dir = dir[:strings.LastIndex(dir, "/")+1]
				p = &pkg{path: f.GoImportPath, name: string(f.GoPackageName), dir: dir, docs: map[string]string{}}
				pkgs[f.GoImportPath] = p
				order = append(order, p)
			}
			var walk func(ms []*protogen.Message)
			walk = func(ms []*protogen.Message) {
				for _, m := range ms {
					for _, fld := range m.Fields {
						if c := oneLine(string(fld.Comments.Leading)); c != "" {
							p.docs[string(fld.Desc.FullName())] = c
						}
					}
					walk(m.Messages)
				}
			}
			walk(f.Messages)
		}
		for _, p := range order {
			g := gen.NewGeneratedFile(p.dir+"flagdocs.gen.go", p.path)
			g.P("// Code generated by protoc-gen-flagdocs. DO NOT EDIT.")
			g.P()
			g.P("package ", p.name)
			g.P()
			g.P("// FieldDocs is the leading comment of every commented field, by its full name.")
			g.P("var FieldDocs = map[string]string{")
			names := make([]string, 0, len(p.docs))
			for n := range p.docs {
				names = append(names, n)
			}
			sort.Strings(names)
			for _, n := range names {
				g.P(fmt.Sprintf("\t%q: %q,", n, p.docs[n]))
			}
			g.P("}")
		}
		return nil
	})
}

// oneLine joins a comment's lines into one sentence run.
func oneLine(c string) string { return strings.Join(strings.Fields(c), " ") }
